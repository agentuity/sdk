// ── Nuxt ─────────────────────────────────────────────────────────────────────

export const nuxtCdnRecipe: ConfigCdnRecipe = {
	label: 'Nuxt',
	configNames: [
		'nuxt.config.ts',
		'nuxt.config.mts',
		'nuxt.config.js',
		'nuxt.config.mjs',
		'nuxt.config.cjs',
	],
	alreadyConfigured: (src) => /\bcdnURL\b/.test(src),
	// Nuxt docs use trailing slash on cdnURL.
	mergeBody: `
	const base = resolved && typeof resolved === 'object' ? resolved : {};
	const app = { ...(base.app || {}) };
	if (app.cdnURL) {
		out = base;
	} else {
		app.cdnURL = origin.endsWith('/') ? origin : origin + '/';
		out = { ...base, app };
	}
`,
	extraEnv: (_origin, base) => ({
		NUXT_APP_CDN_URL: base,
	}),
	writeMissingConfig: (projectDir, logs) => {
		const generated = join(projectDir, 'nuxt.config.ts');
		writeFileSync(
			generated,
			`// Generated by agentuity build — temporary CDN app.cdnURL config.
export default {
	app: {
		cdnURL: process.env.NUXT_APP_CDN_URL || process.env.AGENTUITY_CDN_BASE_URL || undefined,
	},
};
`,
			'utf-8'
		);
		logs.push('✓ Nuxt CDN: wrote temporary nuxt.config.ts with app.cdnURL');
		return () => {
			try {
				unlinkSync(generated);
			} catch {
				/* ignore */
			}
		};
	},
};

// ── SvelteKit ────────────────────────────────────────────────────────────────

/**
 * Declarative adapter-auto → adapter-node (same semantics as frameworks.ts
 * buildFileReplacements). Applied as prePatch so it runs on the real file
 * before the CDN wrap.
 */
function sveltekitAdapterNodePrePatch(configPath: string, logs: string[]): (() => void) | null {
	if (!existsSync(configPath)) return null;
	const original = readFileSync(configPath, 'utf-8');
	if (!original.includes('@sveltejs/adapter-auto')) return null;
	writeFileSync(
		configPath,
		original.replace(/@sveltejs\/adapter-auto/g, '@sveltejs/adapter-node'),
		'utf-8'
	);
	logs.push('✓ SvelteKit: swapped adapter-auto → adapter-node for self-hosting');
	return () => writeFileSync(configPath, original, 'utf-8');
}

export const sveltekitCdnRecipe: ConfigCdnRecipe = {
	label: 'SvelteKit',
	configNames: ['svelte.config.js', 'svelte.config.ts', 'svelte.config.mjs', 'svelte.config.cjs'],
	// Wrapper merge preserves existing paths.assets — no fragile regex tree.
	alreadyConfigured: () => false,
	// SvelteKit requires a plain config object as default export, not a function.
	exportStyle: 'value',
	mergeBody: `
	const base = resolved && typeof resolved === 'object' ? resolved : {};
	const kit = { ...(base.kit || {}) };
	const paths = { ...(kit.paths || {}) };
	if (paths.assets) {
		out = base;
	} else {
		paths.assets = origin;
		kit.paths = paths;
		out = { ...base, kit };
	}
`,
	prePatch: sveltekitAdapterNodePrePatch,
};

// ── prepare helpers bound to recipes ─────────────────────────────────────────

/** Minimal input for CDN prep (full BuildAdapterOptions also works). */
export type CdnPrepInput = {
	projectDir: string;
	logger: { debug: (...args: unknown[]) => void };
	cdnBaseUrl?: string;
	deploymentId?: string;
	env?: NodeJS.ProcessEnv;
};

function bindRecipe(recipe: ConfigCdnRecipe) {
	return (options: CdnPrepInput | BuildAdapterOptions): CdnPrepResult =>
		prepareConfigCdn({
			projectDir: options.projectDir,
			cdnBaseUrl: options.cdnBaseUrl,
			deploymentId: options.deploymentId,
			logger: options.logger,
			env: 'env' in options ? options.env : undefined,
			recipe,
		});
}

export const prepareNextCdnBuild = bindRecipe(nextjsCdnRecipe);
export const prepareAstroCdnBuild = bindRecipe(astroCdnRecipe);
export const prepareNuxtCdnBuild = bindRecipe(nuxtCdnRecipe);
export const prepareSvelteKitCdnBuild = bindRecipe(sveltekitCdnRecipe);
