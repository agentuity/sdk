/**
 * Per-framework CDN config recipes. Each recipe is only the *variance*
 * (which file, which field, optional prePatch). Lifecycle lives in
 * `config-cdn-wrap.ts`.
 */

import { existsSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ConfigCdnRecipe } from './config-cdn-wrap.ts';
import { prepareConfigCdn, type CdnPrepResult } from './config-cdn-wrap.ts';
import type { BuildAdapterOptions } from './types.ts';

// ── Next.js ──────────────────────────────────────────────────────────────────

export const nextjsCdnRecipe: ConfigCdnRecipe = {
	label: 'Next.js',
	configNames: [
		'next.config.js',
		'next.config.mjs',
		'next.config.cjs',
		'next.config.ts',
		'next.config.mts',
	],
	alreadyConfigured: (src) => /\bassetPrefix\b/.test(src),
	mergeBody: `
	if (resolved && typeof resolved === 'object' && resolved.assetPrefix) {
		out = resolved;
	} else {
		out = { ...(resolved && typeof resolved === 'object' ? resolved : {}), assetPrefix: origin };
	}
`,
	writeMissingConfig: (projectDir, logs) => {
		const generated = join(projectDir, 'next.config.js');
		writeFileSync(
			generated,
			`// Generated by agentuity build — temporary CDN assetPrefix config.
/** @type {import('next').NextConfig} */
module.exports = {
	assetPrefix: process.env.AGENTUITY_CDN_ORIGIN?.replace(/\\/+$/, '') || undefined,
};
`,
			'utf-8'
		);
		logs.push('✓ Next.js CDN: wrote temporary next.config.js with assetPrefix');
		return () => {
			try {
				unlinkSync(generated);
			} catch {
				/* ignore */
			}
		};
	},
};

